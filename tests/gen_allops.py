#!/usr/bin/env python3
"""Generate allops.bin + allops.hints: every 65816 opcode in every width state.

Instruction lengths come from this script's own table (WDC W65C816S data
sheet), independent of Capstone, so the round trip cross-checks Capstone's
lengths and ca65's encodings.  Each instruction is its own hinted entry."""
import sys, os
# operand bytes in 8-bit m/x
L = [0]*256
two = {0x00,0x02,0x42} # brk cop wdm signature
for op in range(256):
    lo = op & 0x1F
    n = 0
    # derived per column of the opcode matrix
    col = op & 0x0F
    if col in (0x1,0x3,0x5,0x6,0x7,0x4): n = 1
    elif col in (0xC,0xD,0xE): n = 2
    elif col == 0xF: n = 3
    elif col in (0x9,): n = 1 if (op >> 4) % 2 == 0 else 2      # imm / abs,y
    elif col == 0x0: n = 1 if op not in (0x20,0x40,0x60) else (2 if op == 0x20 else 0)
    elif col == 0x2: n = 1
    elif col in (0x8,0xA,0xB): n = 0
    L[op] = n
fix = {0x20:2,0x22:3,0x40:0,0x60:0,0x62:2,0x82:2,0x44:2,0x54:2,0xD4:1,0xF4:2,0xDC:2,0xFC:2,
       0x7C:2,0x6C:2,0x5C:3,0x4C:2,0xC2:1,0xE2:1,0x89:1,0xA2:1,0x80:1,0xA0:1,0xC0:1,0xE0:1,
       0x0A:0,0x1A:0,0x2A:0,0x3A:0,0x4A:0,0x5A:0,0x6A:0,0x7A:0,0x8A:0,0x9A:0,0xAA:0,0xBA:0,
       0xCA:0,0xDA:0,0xEA:0,0xFA:0,0xDB:0,0xCB:0,0xEB:0,0xFB:0,0x0B:0,0x1B:0,0x2B:0,0x3B:0,
       0x4B:0,0x5B:0,0x6B:0,0x7B:0,0x8B:0,0x9B:0,0xAB:0,0xBB:0}
for k,v in fix.items(): L[k]=v
for op in range(0x10,0x100,0x20): L[op]=1          # branches
for op in range(0x00,0x100,0x20):
    if op not in (0x20,0x40,0x60,0x80,0xA0,0xC0,0xE0): pass
L[0x00]=1; L[0xA0]=1;L[0xC0]=1;L[0xE0]=1
for op in range(0x19,0x100,0x20): L[op]=2           # abs,y
for op in range(0x09,0x100,0x20): L[op]=1           # imm (M)
L[0x89]=1
MDEP = {0x09,0x29,0x49,0x69,0x89,0xA9,0xC9,0xE9}
XDEP = {0xA0,0xA2,0xC0,0xE0}
states = [("m8x8",1,1),("m16x8",0,1),("m8x16",1,0),("m16x16",0,0)]
org = 0x030000
out, hints = bytearray(), ["# generated by gen_allops.py"]
lens = []
for name, m, x in states:
    for op in range(256):
        n = L[op] + (1 if (op in MDEP and m == 0) or (op in XDEP and x == 0) else 0)
        addr = org + len(out)
        hints.append("entry $%06X %s" % (addr, name))
        hints.append("state $%06X %s" % (addr, name))
        b = [op] + [0x12,0x34,0x56][:n]
        if op in (0x10,0x30,0x50,0x70,0x90,0xB0,0xD0,0xF0,0x80): b = [op, 0x00]     # branch to next
        if op in (0x82,0x62): b = [op, 0x00, 0x00]
        out += bytes(b)
d = sys.argv[1] if len(sys.argv) > 1 else "."
open(os.path.join(d,"allops.bin"),"wb").write(out)
open(os.path.join(d,"allops.hints"),"w").write("\n".join(hints)+"\n")
open(os.path.join(d,"allops.org"),"w").write("$%06X\n" % org)
