#!/usr/bin/env python3
"""All-opcode fixtures for the 8-bit CPUs: allops_6502.bin and allops_65c02.bin
(org $0200), each instruction a hinted entry.  Lengths come from this script's
own tables (MOS 6502 programming manual; WDC W65C02S data sheet), independent
of Capstone; the round trip through ca65 (.setcpu "6502" / "65C02") checks the
encodings.  BRK is counted as 2 bytes (opcode + signature), as Capstone and
dumpapple treat it."""
import os, sys
d = sys.argv[1] if len(sys.argv) > 1 else "."
L6502 = {}
def add(t, ops, n):
    for o in ops: t[o] = n
# ALU group (cc=01): (zp,x) zp #imm abs (zp),y zp,x abs,y abs,x
for aaa in range(8):
    base = aaa << 5 | 1
    for bbb, n in enumerate([2, 2, 2, 3, 2, 2, 3, 3]):
        op = base | bbb << 2
        if op == 0x89: continue           # STA #imm does not exist
        L6502[op] = n
# RMW group (cc=10)
add(L6502, [0x06, 0x26, 0x46, 0x66, 0xC6, 0xE6, 0x86, 0xA6], 2)        # zp
add(L6502, [0x0E, 0x2E, 0x4E, 0x6E, 0xCE, 0xEE, 0x8E, 0xAE], 3)        # abs
add(L6502, [0x16, 0x36, 0x56, 0x76, 0xD6, 0xF6, 0x96, 0xB6], 2)        # zp,x / zp,y
add(L6502, [0x1E, 0x3E, 0x5E, 0x7E, 0xDE, 0xFE, 0xBE], 3)              # abs,x / ldx abs,y
add(L6502, [0x0A, 0x2A, 0x4A, 0x6A, 0x8A, 0xAA, 0xCA, 0xEA, 0x9A, 0xBA], 1)
add(L6502, [0xA2], 2)
# control group (cc=00)
add(L6502, [0x24, 0x84, 0xA4, 0xC4, 0xE4, 0x94, 0xB4, 0xA0, 0xC0, 0xE0], 2)
add(L6502, [0x2C, 0x4C, 0x6C, 0x8C, 0xAC, 0xCC, 0xEC, 0xBC, 0x20], 3)
add(L6502, [0x10, 0x30, 0x50, 0x70, 0x90, 0xB0, 0xD0, 0xF0], 2)
add(L6502, [0x40, 0x60] + list(range(0x08, 0x100, 0x10)), 1)
add(L6502, [0x00], 2)
assert len(L6502) == 151, len(L6502)
L65C02 = dict(L6502)
add(L65C02, [0x12, 0x32, 0x52, 0x72, 0x92, 0xB2, 0xD2, 0xF2], 2)       # (zp)
add(L65C02, [0x89, 0x34, 0x64, 0x74, 0x04, 0x14, 0x80], 2)             # bit #, bit zp,x, stz, tsb/trb zp, bra
add(L65C02, [0x3C, 0x9C, 0x9E, 0x0C, 0x1C, 0x7C], 3)
add(L65C02, [0x1A, 0x3A, 0x5A, 0x7A, 0xDA, 0xFA, 0xCB, 0xDB], 1)       # inc/dec a, phy ply phx plx, wai stp
add(L65C02, [o << 4 | 0x07 for o in range(16)], 2)                    # RMBn/SMBn zp
add(L65C02, [o << 4 | 0x0F for o in range(16)], 3)                    # BBRn/BBSn zp,rel
assert len(L65C02) == 212, len(L65C02)   # W65C02S: 212 defined opcodes
BR = {0x10, 0x30, 0x50, 0x70, 0x90, 0xB0, 0xD0, 0xF0, 0x80}
for name, tab in (("6502", L6502), ("65c02", L65C02)):
    org, out, hints = 0x0200, bytearray(), ["# generated by gen_allops_8bit.py"]
    for op in sorted(tab):
        n = tab[op]
        hints.append("entry $%04X" % (org + len(out)))
        if op in BR: b = [op, 0x00]
        elif (op & 0x0F) == 0x0F and name == "65c02": b = [op, 0x12, 0x00]
        else: b = [op, 0x12, 0x34][:n]
        out += bytes(b)
    open(os.path.join(d, "allops_%s.bin" % name), "wb").write(out)
    open(os.path.join(d, "allops_%s.hints" % name), "w").write("\n".join(hints) + "\n")
